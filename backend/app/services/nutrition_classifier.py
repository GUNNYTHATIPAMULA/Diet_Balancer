"""Classify a food into nutrition categories from its VERIFIED values per 100 g.

Deterministic and explainable on purpose: categories are derived from numbers that
come from a food-composition database, never generated by a language model. A food
can be in several categories (eggs: protein + fat).

Rules (per 100 g)
  protein        protein >= 10 g, or protein provides >= 20 % of energy
  carbohydrates  carbohydrates provide >= 40 % of energy
  fat            fat provides >= 35 % of energy
  fiber          fiber >= 6 g
  mixed          no single macronutrient provides >= 50 % of energy and 2+ macros qualify
Primary category: protein when it qualifies AND supplies >= 25 % of energy (how
nutritionists usually group eggs, paneer, chicken), otherwise the macronutrient with
the largest share of energy.
"""
from dataclasses import dataclass, field

LABELS = {"protein": "Protein", "carbohydrates": "Carbohydrates", "fat": "Fat", "fiber": "Fiber",
          "mixed": "Mixed nutrition"}


@dataclass
class Classification:
    primary: str | None
    categories: list[str]
    energy_share: dict[str, float]
    reasons: list[str] = field(default_factory=list)


def classify(*, protein: float, carbs: float, fat: float, fiber: float = 0.0) -> Classification:
    protein, carbs, fat, fiber = (max(float(v or 0), 0.0) for v in (protein, carbs, fat, fiber))
    energy = {"protein": protein * 4, "carbohydrates": carbs * 4, "fat": fat * 9}
    total = sum(energy.values())
    if total <= 0:
        return Classification(primary=None, categories=[], energy_share={k: 0.0 for k in energy},
                              reasons=["No energy-providing nutrients recorded."])
    share = {k: round(v / total, 3) for k, v in energy.items()}

    qualifies, reasons = [], []
    if protein >= 10 or share["protein"] >= 0.20:
        qualifies.append("protein")
        reasons.append(f"{protein:g} g protein per 100 g ({share['protein']:.0%} of energy).")
    if share["carbohydrates"] >= 0.40:
        qualifies.append("carbohydrates")
        reasons.append(f"Carbohydrates supply {share['carbohydrates']:.0%} of energy.")
    if share["fat"] >= 0.35:
        qualifies.append("fat")
        reasons.append(f"Fat supplies {share['fat']:.0%} of energy.")

    if "protein" in qualifies and share["protein"] >= 0.25:
        primary = "protein"
    elif qualifies:
        primary = max(qualifies, key=lambda k: share[k])
    else:
        primary = max(share, key=share.get)
        qualifies.append(primary)
        reasons.append(f"{LABELS[primary]} is the largest source of energy ({share[primary]:.0%}).")

    ordered = [primary] + sorted([c for c in qualifies if c != primary], key=lambda k: -share[k])
    if fiber >= 6:
        ordered.append("fiber")
        reasons.append(f"High in fiber ({fiber:g} g per 100 g).")
    if max(share.values()) < 0.50 and len([c for c in ordered if c in energy]) >= 2:
        ordered.append("mixed")
        reasons.append("No single macronutrient dominates.")
    return Classification(primary=primary, categories=ordered, energy_share=share, reasons=reasons)


def classify_food(food) -> Classification:
    return classify(protein=food.protein_per_100g, carbs=food.carbs_per_100g, fat=food.fat_per_100g,
                    fiber=food.fiber_per_100g)
